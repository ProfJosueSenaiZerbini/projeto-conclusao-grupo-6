export const curadoria = Object.freeze(dados);
export function montarSelo(slug) {
  const [
    sigla,
    forma,
    paleta,
    simbolo,
    fonte,
    textura,
    arranjo,
    legenda,
    motivo,
  ] = curadoria[slug];
  const [escuro, luz, traço] = tinta[paleta];
  const lado = arranjo === "lateral";
  const c = baseSelo(forma, paleta);
  c.fundo = {
    tipo: paleta === "prata" || paleta === "areia" ? "solido" : "linear",
    cor: escuro,
    segunda: luz,
    angulo: lado ? 42 : 145,
  };
  c.bordas = [
    { tipo: "solida", cor: traço, espessura: 2.25, recuo: 1, opacidade: 91 },
    {
      tipo:
        textura === "pontos"
          ? "pontilhada"
          : textura === "riscado"
            ? "tracejada"
            : "solida",
      cor: traço,
      espessura: 0.8,
      recuo: 8,
      opacidade: 45,
    },
  ];
  c.textura = {
    tipo: textura,
    opacidade: 16,
    escala: textura === "pontos" ? 4 : 7,
  };
  c.acabamento = textura === "riscado" ? "carimbo" : "fosco";
  const estreita = forma === "gota" || forma === "prisma";
  c.camadas.push(
    novaCamada("simbolo", simbolo, {
      nome: "Símbolo · " + simbolo.replaceAll("-", " "),
      x: lado ? 30 : 50,
      y: lado ? 45 : 29,
      escala: lado ? 60 : 74,
      cor: traço,
    }),
    novaCamada("letras", sigla, {
      nome: "Monograma",
      x: lado ? 64 : 50,
      y: lado ? 48 : 56,
      escala: lado || estreita ? 91 : 111,
      fonte,
      cor: traço,
      espaco: sigla.length === 3 ? 0 : 1,
    }),
    novaCamada("texto", legenda, {
      nome: "Legenda para tamanho grande",
      x: lado ? 58 : 50,
      y: estreita ? 72 : 76,
      escala: legenda.length > 11 ? 58 : 73,
      peso: 650,
      fonte: "sans",
      cor: traço,
      espaco: 1,
      compacta: false,
    })
  );
  return c;
}
